-- TutorLink — Rosebank's official qualifications and modules
--
-- The Bloemfontein campus list: every qualification (with its faculty) and the modules in it,
-- each with the year of study it belongs to. Students pick their qualification and year when they
-- sign up, and that year's modules are added for them (electives, like home languages, they tick
-- themselves). The module list is now admin-only. New views: students enrolled in a module who
-- haven't been to a session, demand per module, and reach by faculty.

/* ---------- codes as Rosebank writes them ---------- */

-- Most codes are 4 letters + 4 digits, but a few aren't (ACAD121, XBLAW5119, XADAD7112, LSM6411).
alter table public.modules drop constraint modules_code_check;
alter table public.modules add constraint modules_code_check check (code ~ '^[A-Z]{3,5}[0-9]{3,4}$');
-- Qualification codes too: e.g. 117914 is just a number.
alter table public.qualifications drop constraint qualifications_code_check;
alter table public.qualifications add constraint qualifications_code_check check (code ~ '^[A-Z0-9]{2,10}$');

/* ---------- the catalogue ---------- */

alter table public.qualifications add column faculty text;

create table public.qualification_modules (
  qualification_code text not null references public.qualifications (code) on update cascade,
  module_code        text not null references public.modules (code) on update cascade,
  year               smallint check (year between 1 and 4),
  elective           boolean not null default false,
  primary key (qualification_code, module_code)
);
create index on public.qualification_modules (module_code);
alter table public.qualification_modules enable row level security;
create policy "everyone signed in reads the catalogue" on public.qualification_modules
  for select to authenticated using (true);
create policy "admin manages the catalogue" on public.qualification_modules
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

alter table public.profiles add column study_year smallint check (study_year between 1 and 4);

/* ---------- the module and qualification lists are admin's ---------- */

drop policy "anyone signed in can add a module" on public.modules;
create policy "admin adds modules" on public.modules
  for insert to authenticated with check (public.is_admin());

create or replace function public.add_module(p_code text, p_name text) returns text
language plpgsql set search_path = '' as $$
declare v_code text := upper(btrim(p_code));
begin
  if not public.is_admin() then raise exception 'Only admin can add modules' using errcode = '42501'; end if;
  insert into public.modules (code, name) values (v_code, p_name) on conflict (code) do nothing;
  return v_code;
end $$;

create or replace function public.add_qualification(p_code text, p_name text) returns text
language plpgsql security definer set search_path = '' as $$
declare v_code text := upper(btrim(p_code));
begin
  if not public.is_admin() then raise exception 'Only admin can add qualifications' using errcode = '42501'; end if;
  if v_code !~ '^[A-Z0-9]{2,10}$' then raise exception 'Qualification codes are letters and digits, e.g. DISD0601'; end if;
  insert into public.qualifications (code, name) values (v_code, btrim(p_name)) on conflict (code) do nothing;
  return v_code;
end $$;

/* ---------- a student's qualification and year ---------- */

-- Sets them, and adds that year's modules (not the electives). Returns how many were added.
create function public.set_my_study(p_qualification text, p_year int) returns int
language plpgsql security definer set search_path = '' as $$
declare v_uid uuid := (select auth.uid()); v_n int;
begin
  if not exists (select 1 from public.profiles where id = v_uid and role = 'student') then
    raise exception 'Only students choose a qualification';
  end if;
  if not exists (select 1 from public.qualifications where code = p_qualification and not hidden) then
    raise exception 'Choose a qualification from the list';
  end if;
  if p_year is null or p_year < 1 or p_year > 4 then raise exception 'Choose your year of study'; end if;
  update public.profiles set qualification_code = p_qualification, study_year = p_year where id = v_uid;
  insert into public.student_modules (student_id, module_code)
    select v_uid, module_code from public.qualification_modules
    where qualification_code = p_qualification and year = p_year and not elective
  on conflict do nothing;
  get diagnostics v_n = row_count;
  return v_n;
end $$;

/* ---------- who's missing: enrolled, but no check-in yet ---------- */

-- For a module's lecturers and admin: students who have the module but haven't been to any of its
-- sessions (of that kind) this semester, with how many were held.
create function public.module_missing(p_semester uuid, p_module text, p_kind text default 'tutorial')
returns table (student_number text, full_name text, qualification_code text, held int)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not (public.is_admin() or public.teaches(p_module)) then return; end if;
  return query
    select p.student_number, p.full_name, p.qualification_code,
      (select count(*)::int from public.sessions s where s.semester_id = p_semester and s.module_code = p_module
        and s.kind = p_kind and s.status in ('logged', 'confirmed', 'paid'))
    from public.student_modules sm join public.profiles p on p.id = sm.student_id
    where sm.module_code = p_module and p.role = 'student' and p.student_number is not null
      and not exists (select 1 from public.attendance a join public.sessions s on s.id = a.session_id
                      where a.student_number = p.student_number and s.module_code = p_module
                        and s.kind = p_kind and s.semester_id = p_semester)
    order by p.full_name;
end $$;

/* ---------- demand per module (admin) ---------- */

create function public.module_demand()
returns table (module_code text, students int, tutors int, qualifications int)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.is_admin() then raise exception 'Admin only' using errcode = '42501'; end if;
  return query
    select m.code,
      (select count(*)::int from public.student_modules sm where sm.module_code = m.code),
      (select count(*)::int from public.tutor_modules tm where tm.module_code = m.code),
      (select count(*)::int from public.qualification_modules qm where qm.module_code = m.code)
    from public.modules m where not m.hidden;
end $$;

/* ---------- reach by faculty ---------- */

-- Runs as the person asking, so admin sees every faculty and a lecturer only their modules' students.
create function public.attendance_by_faculty(p_semester uuid, p_kind text default 'tutorial')
returns table (faculty text, students int, checkins int)
language sql stable security invoker set search_path = '' as $$
  select coalesce(q.faculty, 'Other'), count(distinct a.student_number)::int, count(*)::int
  from public.attendance a
  join public.sessions s on s.id = a.session_id
  left join public.qualifications q on q.code = a.qualification_code
  where s.semester_id = p_semester and s.kind = p_kind and s.status in ('logged', 'confirmed', 'paid')
  group by 1
  order by 2 desc, 1
$$;

revoke execute on function public.set_my_study(text, int) from public, anon;
revoke execute on function public.module_missing(uuid, text, text) from public, anon;
revoke execute on function public.module_demand() from public, anon;
revoke execute on function public.attendance_by_faculty(uuid, text) from public, anon;
revoke execute on function public.add_qualification(text, text) from public, anon;
grant execute on function public.set_my_study(text, int) to authenticated;
grant execute on function public.module_missing(uuid, text, text) to authenticated;
grant execute on function public.module_demand() to authenticated;
grant execute on function public.attendance_by_faculty(uuid, text) to authenticated;
grant execute on function public.add_qualification(text, text) to authenticated;

